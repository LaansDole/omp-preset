#!/usr/bin/env python3
"""Regenerate the agents table in README.md from agents/*.md frontmatter.

Usage:
  scripts/gen-agents-table.py          # rewrite README.md in place
  scripts/gen-agents-table.py --check  # exit 1 if README.md is stale (CI)

The table lives between the AGENTS_TABLE markers in README.md. Stdlib only.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
AGENTS = ROOT / "agents"
CONFIG = ROOT / "config.yml"
START = "<!-- AGENTS_TABLE:START (generated by scripts/gen-agents-table.py, do not edit) -->"
END = "<!-- AGENTS_TABLE:END -->"


def frontmatter(path: Path) -> dict:
    """Top-level scalar keys of the YAML frontmatter (nested blocks are skipped)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    out = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        m = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def unquote(v: str) -> str:
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        try:
            return json.loads(v) if v[0] == '"' else v[1:-1]
        except json.JSONDecodeError:
            return v[1:-1]
    return v


def config_overrides() -> dict:
    """task.agentModelOverrides from config.yml (stdlib-only, indentation-based)."""
    try:
        lines = CONFIG.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return {}
    out, in_task, in_block = {}, False, False
    for line in lines:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        if indent == 0:
            in_task, in_block = line.split(":")[0] == "task", False
        elif in_task and indent == 2:
            in_block = line.strip().startswith("agentModelOverrides:")
        elif in_block and indent == 4:
            m = re.match(r"^\s+([\w-]+):\s*(.+)$", line)
            if m:
                out[m.group(1)] = unquote(m.group(2).strip())
    return out


def model_cell(v: str) -> str:
    if not v:
        return "inherits `default`"
    try:
        models = json.loads(v) if v.startswith("[") else [unquote(m.strip()) for m in v.split(",")]
    except json.JSONDecodeError:
        models = [v]
    first, rest = models[0], models[1:]
    cell = f"`{first}`"
    if rest:
        cell += " (fallback: " + ", ".join(f"`{m}`" for m in rest) + ")"
    return cell


def build_table() -> str:
    overrides = config_overrides()
    rows = ["| Agent | What it does | Model (runs on) |", "|---|---|---|"]
    for path in sorted(AGENTS.glob("*.md"), key=lambda p: p.stem):
        fm = frontmatter(path)
        name = unquote(fm.get("name", path.stem))
        desc = unquote(fm.get("description", "")).replace("|", "\\|")
        if name in overrides:
            model = f"`{overrides[name]}` (config override)"
        else:
            model = model_cell(fm.get("model", ""))
        rows.append(
            f"| [`{name}`](agents/{path.name}) | {desc} | {model} |"
        )
    return "\n".join(rows)


def main() -> int:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"README.md is missing the {START!r} / {END!r} markers", file=sys.stderr)
        return 2
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{build_table()}\n{END}{tail}"
    if new == text:
        return 0
    if "--check" in sys.argv:
        print("README.md agents table is stale: run scripts/gen-agents-table.py", file=sys.stderr)
        return 1
    README.write_text(new, encoding="utf-8")
    print("README.md agents table updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
